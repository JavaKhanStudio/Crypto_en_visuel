#!/usr/bin/env python3
"""r208: the way back of the bridge. A shape as bridge JSON (assets/shapes/<item>.json, r207's format,
see export.gd) is written as a GDScript builder ASSET in the style of Shadow's Items*.gd: one
`static func <item>(cfg: Dictionary) -> Node3D` that rebuilds every part through Prim.box()/Prim.cyl()
with its tint and emission, keeps the named nodes (Fan, RackStatus…) that ItemView animates, and loads
from anywhere Shadow's res:// is the project (godot --path /home/simon/Shadow).
    tools/godot_bridge/to_gdscript.py assets/shapes/server_rack.json [out/godot]  -> out/godot/server_rack.gd
Only what Prim can say is written: a box, a capped-or-not cylinder, the retro shader with the cfg's
gloss/snap/toon. Anything else (a raw mesh, another shader, a scaled node, a part whose gloss is not
the cfg's) is refused with its path, never approximated: tools/godot_bridge/roundtrip.gd proves the rest."""
import json, math, os, sys

DEFAULTS = {"glossiness": .35, "snap_strength": 0.0, "toon_steps": 0.0}   # what Prim takes from an empty cfg

def num(x):
    s = f"{x:.6f}".rstrip("0").rstrip(".")
    return "0.0" if s in ("-0", "0") else (s if "." in s else s + ".0")

def v3(a): return f"Vector3({', '.join(num(x) for x in a)})"

def euler_yxz(m):
    """Godot's rotation_degrees (Basis.get_euler, order YXZ) of a column-major 4x4."""
    R = lambda r, c: m[4 * c + r]
    s = R(1, 2)
    if s < 1 - 1e-7:
        if s > -1 + 1e-7: x, y, z = math.asin(-s), math.atan2(R(0, 2), R(2, 2)), math.atan2(R(1, 0), R(1, 1))
        else: x, y, z = math.pi / 2, math.atan2(R(0, 1), R(0, 0)), 0.0
    else: x, y, z = -math.pi / 2, -math.atan2(R(0, 1), R(0, 0)), 0.0
    return [math.degrees(a) for a in (x, y, z)]

def check(n, path):
    m = n["m"]
    for c in range(3):
        if abs(math.sqrt(sum(m[4 * c + i] ** 2 for i in range(3))) - 1) > 1e-5: sys.exit(f"refused: {path} is scaled")
    if "mesh" in n:
        mat, kind = n["mat"], n["mesh"]["kind"]
        if kind not in ("box", "cylinder"): sys.exit(f"refused: {path} is a {kind} mesh, Prim has no builder for it")
        if mat.get("shader") != "retro.gdshader": sys.exit(f"refused: {path} wears {mat.get('shader')}, not Prim's retro shader")
        for k, v in DEFAULTS.items():
            if abs(mat.get(k, v) - v) > 1e-6: sys.exit(f"refused: {path} has {k} {mat[k]}, Prim takes it from cfg")

class Writer:
    def __init__(self): self.lines, self.k = [], 0
    def var(self, base): self.k += 1; return f"{base}{self.k}"
    def node(self, n, parent, path, ind="\t"):
        check(n, path)
        m, name = n["m"], n.get("name")
        pos, rot = [m[12], m[13], m[14]], euler_yxz(m)
        if "mesh" in n:
            me, mat = n["mesh"], n["mat"]
            emis, ecol = mat.get("emission_amount", 0.0), mat.get("emission_color", [0, 0, 0])
            tail = f", {num(emis)}, {v3(ecol)}" if emis or any(ecol) else ""
            if me["kind"] == "box":
                call = f"Prim.box({v3(me['size'])}, {v3(pos)}, {v3(rot)}, {v3(mat['tint'])}, cfg{tail})"
            else:
                cb, ct = me["caps"][1], me["caps"][0]
                call = (f"Prim.cyl({num(me['bottom'])}, {num(me['height'])}, {v3(pos)}, {v3(mat['tint'])}, cfg, {me['segs']}, "
                        f"{num(emis)}, {v3(ecol)}, {v3(rot)}, {num(me['top'])}, {str(cb).lower()}, {str(ct).lower()})")
        else:
            call = None
        if not name and "children" not in n:
            self.lines.append(f"{ind}{parent}.add_child({call})"); return
        v = self.var("n")
        if call: self.lines.append(f"{ind}var {v} := {call}")
        else:
            self.lines.append(f"{ind}var {v} := Node3D.new()")
            if any(abs(x) > 1e-9 for x in pos): self.lines.append(f"{ind}{v}.position = {v3(pos)}")
            if any(abs(x) > 1e-9 for x in rot): self.lines.append(f"{ind}{v}.rotation_degrees = {v3(rot)}")
        if name: self.lines.append(f'{ind}{v}.name = "{name}"')
        self.lines.append(f"{ind}{parent}.add_child({v})")
        for i, c in enumerate(n.get("children", [])): self.node(c, v, f"{path}/{c.get('name', i)}")

def main():
    src = sys.argv[1]; out = sys.argv[2] if len(sys.argv) > 2 else "out/godot"
    doc = json.load(open(src)); item = doc["item"]; w = Writer()
    for i, n in enumerate(doc["nodes"]): w.node(n, "root", f"{item}/{n.get('name', i)}")
    head = [f"# GENERATED by deux-generaux tools/godot_bridge/to_gdscript.py from {os.path.basename(src)} (r208):",
            f"# {doc['parts']} parts, style {doc['style']}. Edit the JSON (or the three.js side), not this file.",
            "extends RefCounted", "", 'const Prim := preload("res://scripts/items/Prim.gd")', "",
            f"static func {item}(cfg: Dictionary) -> Node3D:", "\tvar root := Node3D.new()"]
    os.makedirs(out, exist_ok=True); path = os.path.join(out, item + ".gd")
    open(path, "w").write("\n".join(head + w.lines + ["\treturn root", ""]))
    print(f"[to_gdscript] {path}: {doc['parts']} parts")

main()
